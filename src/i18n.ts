import { ref } from 'vue'

export type Locale = 'en' | 'de'

const _locale = ref<Locale>(
  (localStorage.getItem('shyboti_lang') as Locale) ?? 'de'
)

export function setLocale(l: Locale) {
  _locale.value = l
  localStorage.setItem('shyboti_lang', l)
}

export function useLocale() {
  return { locale: _locale, setLocale }
}

