export function useI18n() {
  // >>> optional {placeholder} substitution - lets DE reorder words
  // >>> ("vor {time}") relative to EN ("{time} ago") instead of just concatenating
  function t(key: string, params?: Record<string, string | number>): string {
    const raw =
      translations[_locale.value][key] ?? translations["en"][key] ?? key;
    if (!params) return raw;
    return raw.replace(/\{(\w+)\}/g, (m, name) =>
      name in params ? String(params[name]) : m,
    );
  }
  return { t, locale: _locale };
}
